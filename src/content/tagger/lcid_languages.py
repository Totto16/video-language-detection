def get_lcid_lookup_tables() -> tuple[dict[str, int], dict[int, str]]:
    dict1: dict[str, int] = {}
    dict2: dict[int, str] = {}

    for entry in raw_lcid_languages:
        dict1[entry[5]] = entry[3]
        dict2[entry[3]] = entry[5]

    return (dict1, dict2)


lcid_language_lookups: tuple[dict[str, int], dict[int, str]] = get_lcid_lookup_tables()


# Microsoft Language CID
# see https://learn.microsoft.com/en-us/openspecs/windows_protocols/ms-lcid/70feba9f-294e-491e-b6eb-56532684c37f
# https://winprotocoldoc.z19.web.core.windows.net/MS-LCID/%5bMS-LCID%5d.pdf
class LCID:
    @staticmethod
    def decode_language(value: int) -> str:
        return lcid_language_lookups[1].get(value, "und")

    @staticmethod
    def encode_language(code: str) -> int:
        return lcid_language_lookups[0].get(code, 0)
